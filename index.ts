export function formatNumberLocale(value: number, lang: Language): string {
  if (lang === 'ar') {
    return new Intl.NumberFormat('ar-EG').format(value);
  }
  return new Intl.NumberFormat('en-US').format(value);
}

export function formatDurationMinutes(minutes: number, lang: Language): string {
  const hrs = Math.floor(minutes / 60);
  const mins = Math.round(minutes % 60);
  if (lang === 'ar') {
    if (hrs > 0 && mins > 0) {
      return `${formatNumberLocale(hrs, 'ar')} س و ${formatNumberLocale(mins, 'ar')} د`;
    }
    if (hrs > 0) {
      return `${formatNumberLocale(hrs, 'ar')} ساعة`;
    }
    return `${formatNumberLocale(mins, 'ar')} دقيقة`;
  } else {
    if (hrs > 0 && mins > 0) {
      return `${hrs}h ${mins}m`;
    }
    if (hrs > 0) {
      return `${hrs}h`;
    }
    return `${mins}m`;
  }
}

export function formatClockMMSS(totalSeconds: number, lang: Language): string {
  const safe = Math.max(0, Math.floor(totalSeconds));
  const mins = Math.floor(safe / 60);
  const secs = safe % 60;
  const mm = String(mins).padStart(2, '0');
  const ss = String(secs).padStart(2, '0');
  if (lang === 'ar') {
    const mapDigit = (str: string) =>
      str.replace(/\d/g, (d) => '٠١٢٣٤٥٦٧٨٩'[Number(d)]);
    return `${mapDigit(mm)}:${mapDigit(ss)}`;
  }
  return `${mm}:${ss}`;
}

export function formatDateLocale(dateOrTimestamp: number | string, lang: Language): string {
  const d = typeof dateOrTimestamp === 'string' ? new Date(dateOrTimestamp) : new Date(dateOrTimestamp);
  if (Number.isNaN(d.getTime())) return String(dateOrTimestamp);
  return new Intl.DateTimeFormat(lang === 'ar' ? 'ar-EG' : 'en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  }).format(d);
}
